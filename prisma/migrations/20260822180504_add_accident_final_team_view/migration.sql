-- เหตุหนึ่งครั้งอาจมีหลายชุดปฏิบัติการ: ชุดระดับต่ำไปถึงก่อนแล้ว "ส่งต่อชุดปฏิบัติการระดับสูงกว่า"
-- ตารางดิบจึงมีหลายแถวต่อผู้ป่วยหนึ่งคน view นี้คัดเหลือเฉพาะชุดสุดท้ายที่รับช่วง
--
-- เรียง 4 ชั้นเพราะกติกาชั้นเดียวไม่พอกับข้อมูลจริง:
--   1. แถวที่ผลเป็น "ส่งต่อ" ไปอยู่ท้ายเสมอ — ตามนิยามแล้วไม่ใช่ชุดสุดท้าย
--   2. ใครถึงโรงพยาบาลทีหลังคือปลายทาง — บางเหตุมี "รักษา-นำส่ง" สองแถว (ส่งต่อระหว่าง รพ.)
--      ซึ่ง op_no ของชุดหลังไม่ได้มากกว่าเสมอไป
--   3. เวลาออกจากเหตุ ใช้กับเคสที่ไม่ได้นำส่ง จึงไม่มีเวลาถึงโรงพยาบาล
--   4. op_no ปิดท้ายให้ผลคงที่ ไม่แกว่งตามลำดับที่ Postgres คืนแถวมา
CREATE VIEW "accident_final_team" AS
SELECT *
FROM (
  SELECT
    a.*,
    row_number() OVER (
      PARTITION BY a.incident_no, a.patient_no
      ORDER BY
        (a.op_result = 'รักษา-ส่งต่อชุดปฏิบัติการระดับสูงกว่า'),
        a.time_arrived_hospital DESC NULLS LAST,
        a.time_left_scene DESC NULLS LAST,
        a.op_no DESC
    ) AS team_rank
  FROM "accident" a
) ranked
WHERE ranked.team_rank = 1;
